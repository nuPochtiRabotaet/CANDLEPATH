"""Deterministic report rendering. The connected LLM interprets these sourced results."""

def render_report(result):
    i, p, f, d = (result[k] for k in ['instrument','parameters','scenario_frequencies','net_return_distribution'])
    status = 'ИСКУССТВЕННЫЕ ДАННЫЕ' if i['demo_data'] else 'MOEX ISS, нескорректированные цены'
    return f"""# Исследование {i['symbol']}

Данные: {status}. Последнее наблюдение: {i['last_observation_date']}; режим: {i['board']}.
Источник: {i['data_source']}. SHA-256 истории: {i.get('history_sha256') or 'не предоставлен'}.
Предупреждения о покрытии истории: {'; '.join(i.get('data_warnings', [])) or 'нет дополнительных'}.

Рассчитано {p['simulated_paths']} траекторий на {p['horizon_trading_days']} торговых дней, seed={p['seed']}.
Цель раньше стопа достигнута в {f['target_first']:.1%} сценариев, стоп раньше цели — в {f['stop_first']:.1%};
убыточных результатов после условных издержек — {f['net_loss']:.1%}.
Медиана итоговой доходности: {d['median_pct']:+.2f}%; 5-й и 95-й процентили: {d['p05_pct']:+.2f}% / {d['p95_pct']:+.2f}%.

Это частоты внутри выбранной модели, а не оценка реальных вероятностей будущего заработка.
Проверяются только дневные закрытия. Стоп не гарантирует размер убытка.
Дивиденды, сплиты, налоги, реальная ликвидность и исполнение заявок не моделируются.

Для интерпретации ИИ: разделите наблюдаемые факты, допущения модели и неизвестные факторы.
Сравните издержки и чувствительность к периоду истории. Не выдавайте частоты модели за торговый сигнал.
"""
